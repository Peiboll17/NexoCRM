import { db } from "@/lib/db";
import { getSessionUser, UNAUTHORIZED } from "@/lib/auth";
import { ensureWeeklyAlert } from "@/lib/weekly-alerts";

/**
 * GET /api/alerts
 * - Comprobación de la alerta semanal automática: si esta semana aún no
 *   se ha enviado, se genera aquí (lazy cron al abrir el CRM).
 * - Devuelve la bandeja de notificaciones del usuario en sesión.
 */
export async function GET() {
  const me = await getSessionUser();
  if (!me) return UNAUTHORIZED();

  const autoGenerated = await ensureWeeklyAlert();

  const [notifications, unreadCount] = await Promise.all([
    db.notification.findMany({
      where: { userId: me.id },
      orderBy: { createdAt: "desc" },
      take: 20,
    }),
    db.notification.count({ where: { userId: me.id, readAt: null } }),
  ]);

  return Response.json({ notifications, unreadCount, autoGenerated });
}
